/**
 * The Huawei CodeArts channel.
 *
 * ## What is different about this one
 *
 * 1. **Authentication is a request signature, not a bearer.** The credential is
 *    an AK/SK/security-token triple and every request is signed with
 *    `SDK-HMAC-SHA256`.
 * 2. **Two details of that signature look wrong and must be kept.** The signed
 *    `uri` gets a trailing `/` appended when it lacks one, and the date stamp is
 *    an ISO string with `-` and `:` removed. "Fixing" either one makes every
 *    request 401 — the server verifies against the same rules.
 * 3. **Free-tier models need `maas_type: benefit`, and that header is signed.**
 *    Adding it to the request without adding it to the signature fails
 *    verification; adding it to the signature without sending it fails too.
 *
 * ## Sign-in
 *
 * A browser-redirect flow whose callback URL is a parameter the caller supplies,
 * so this package hosts the listener itself. The resulting credential cannot be
 * renewed silently — the ticket response carries no refresh material — which is
 * reported honestly rather than papered over.
 *
 * @module pi-connect-free/providers/codearts
 */

import { createHash, createHmac } from 'node:crypto'
import { createServer } from 'node:http'

import { FreeModelError, KIND } from './types.js'
import { readErrorBody, httpError } from '../http.js'
import { str, num } from '../device-login.js'
import { readCredential, writeCredential, clearCredential, isExpired } from '../credential-store.js'

const WHAT = 'CodeArts'
const CHAT_BASE = 'https://snap-access.cn-north-4.myhuaweicloud.com/api/v2'
const ENGINE_BASE = 'https://snap-access.cn-north-4.myhuaweicloud.com'
const GATEWAY_CONFIG_URL = 'https://opengw.developer.huaweicloud.com/api/v1/gateway/config'
const BUILTIN_MODELS_URL = `${ENGINE_BASE}/v1/model/builtin`

function sha256Hex(bytes) {
  return createHash('sha256').update(bytes).digest('hex')
}

function hmacHex(key, data) {
  return createHmac('sha256', key).update(data).digest('hex')
}

/**
 * Sign one request with Huawei's `SDK-HMAC-SHA256`.
 *
 * The canonical request is six sections joined by `\n`, with an empty line
 * between the header block and the signed-header list. Every byte of it is
 * compared by the server.
 *
 * @param {{ak: string, sk: string, securityToken: string}} keys
 * @param {string} method
 * @param {string} urlStr
 * @param {Uint8Array} body
 * @param {Record<string,string>} [extraHeaders] headers that must also be signed
 * @returns {Promise<Map<string,string>>}
 */
export async function signRequest(keys, method, urlStr, body, extraHeaders) {
  const url = new URL(urlStr)
  // The server signs a trailing slash onto a path that lacks one. This is not a
  // bug to fix: the same rule is applied on verification.
  const uri = url.pathname.endsWith('/') ? url.pathname : `${url.pathname}/`
  const query = url.search.slice(1)
  const dateStamp = new Date().toISOString().replace(/[-:]/g, '').replace(/\.\d+Z$/, 'Z')
  const payloadHash = sha256Hex(body)

  const headers = new Map()
  headers.set('host', url.host)
  headers.set('x-sdk-date', dateStamp)
  headers.set('x-sdk-content-sha256', payloadHash)
  headers.set('x-security-token', keys.securityToken)
  for (const [key, value] of Object.entries(extraHeaders ?? {})) headers.set(key, value)
  if (method.toUpperCase() !== 'GET') headers.set('content-type', 'application/json')

  const signedNames = [...headers.keys()].sort()
  const headerLines = signedNames.map((name) => `${name}:${headers.get(name)}`)
  const canonicalRequest = [method, uri, query, headerLines.join('\n'), '', signedNames.join(';'), payloadHash].join('\n')
  const stringToSign = `SDK-HMAC-SHA256\n${dateStamp}\n${sha256Hex(canonicalRequest)}`
  const signature = hmacHex(keys.sk, stringToSign)
  headers.set('Authorization', `SDK-HMAC-SHA256 Access=${keys.ak},SignedHeaders=${signedNames.join(';')},Signature=${signature}`)
  return headers
}

/** Convert a signed header map into a `Headers`, dropping `host`. */
function toHeaders(signed) {
  const headers = new Headers()
  for (const [key, value] of signed) {
    // `host` is generated by the runtime from the connection target; setting it
    // by hand is ignored or rejected.
    if (key !== 'host') headers.set(key, value)
  }
  return headers
}

function keysOf(credential) {
  const ak = str(credential.extras?.ak)
  const sk = str(credential.extras?.sk)
  if (ak === '' || sk === '') {
    throw new FreeModelError(KIND.auth, `${WHAT} credential is missing its AK/SK; sign in again`)
  }
  return { ak, sk, securityToken: credential.accessToken }
}

/**
 * Run the browser-redirect sign-in.
 *
 * The callback URL is a parameter this package supplies, so it points at a
 * loopback listener here. The listener is torn down as soon as the ticket
 * arrives.
 */
export async function login({ onPrompt, signal, timeoutMs = 300000 } = {}) {
  const state = createHash('sha256').update(String(Date.now()) + Math.random()).digest('hex').slice(0, 16)
  const server = createServer()
  await new Promise((resolve, reject) => {
    server.once('error', reject)
    server.listen(0, '127.0.0.1', () => {
      server.removeListener('error', reject)
      resolve()
    })
  })
  const address = server.address()
  if (address === null || typeof address === 'string') {
    await new Promise((resolve) => server.close(() => resolve()))
    throw new FreeModelError(KIND.transport, `${WHAT} could not open a local callback port`)
  }
  const callbackUrl = `http://127.0.0.1:${address.port}/authentication`

  const secret = await new Promise((resolve, reject) => {
    const timer = setTimeout(() => {
      cleanup()
      reject(new FreeModelError(KIND.timeout, `${WHAT} sign-in timed out; start it again`))
    }, timeoutMs)
    timer.unref?.()
    const onAbort = () => {
      cleanup()
      reject(new FreeModelError(KIND.aborted, `${WHAT} sign-in was cancelled`))
    }
    const cleanup = () => {
      clearTimeout(timer)
      signal?.removeEventListener?.('abort', onAbort)
      server.close()
    }
    signal?.addEventListener('abort', onAbort, { once: true })
    server.on('request', (req, res) => {
      const url = new URL(req.url ?? '/', 'http://127.0.0.1')
      if (url.pathname !== '/authentication') {
        res.writeHead(404).end()
        return
      }
      const returned = url.searchParams.get('secret') ?? ''
      res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' })
      res.end('<meta charset="utf-8"><p>已收到授权，可以关闭此页面。</p>')
      cleanup()
      if (returned === '') {
        reject(new FreeModelError(KIND.auth, `${WHAT} callback carried no ticket`))
        return
      }
      resolve(returned)
    })
    onPrompt?.(callbackUrl)
  })

  // The ticket is exchanged for the AK/SK triple.
  const response = await fetch(`${ENGINE_BASE}/v1/auth/ticket`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ secret }),
    signal,
  })
  if (!response.ok) throw httpError(`${WHAT} ticket exchange`, response, await readErrorBody(response))
  const document = await response.json()
  const data = document?.result ?? document?.data ?? document ?? {}
  const ak = str(data.ak) || str(data.access_key)
  const sk = str(data.sk) || str(data.secret_key)
  const securityToken = str(data.security_token) || str(data.securityToken) || str(data.token)
  if (ak === '' || sk === '' || securityToken === '') {
    throw new FreeModelError(KIND.auth, `${WHAT} ticket exchange returned an incomplete AK/SK/security-token triple`)
  }
  const credential = {
    provider: 'codearts',
    uid: str(data.user_id) || str(data.userId) || `ak:${ak.slice(-8)}`,
    accessToken: securityToken,
    refreshToken: '',
    expiresAt: num(data.expires_at) ?? 0,
    nickname: 'CodeArts',
    source: 'app',
    extras: { ak, sk },
  }
  writeCredential('codearts', credential)
  return credential
}

export function logout() {
  clearCredential('codearts')
}

export async function findCredential() {
  return readCredential('codearts')
}

/**
 * List the roster.
 *
 * Two sources: the gateway config publishes the benefit (free-quota) models,
 * and the builtin endpoint publishes the rest. Both are read because neither
 * alone is the complete set.
 */
export async function listModels(credential, signal) {
  if (isExpired(credential)) throw new FreeModelError(KIND.auth, `${WHAT} credential expired; sign in again`)
  const keys = keysOf(credential)
  const models = []

  const gatewayUrl = `${GATEWAY_CONFIG_URL}?product=codearts`
  const gatewaySigned = await signRequest(keys, 'GET', gatewayUrl, new Uint8Array())
  const gateway = await fetch(gatewayUrl, { headers: toHeaders(gatewaySigned), signal })
    .then((r) => (r.ok ? r.json() : undefined))
    .catch(() => undefined)
  for (const entry of Array.isArray(gateway?.result?.models) ? gateway.result.models : []) {
    const id = str(entry.model_name) || str(entry.id)
    if (id === '') continue
    models.push({
      id,
      name: str(entry.display_name) || id,
      contextWindow: num(entry.context_length) ?? 0,
      maxOutput: num(entry.max_output_tokens) ?? 0,
      supportsImage: entry.supports_vision === true,
      isFree: true,
      // Free-quota models must carry this header on the chat call, and it is
      // part of the signature.
      extras: { maasType: 'benefit' },
    })
  }

  const builtinSigned = await signRequest(keys, 'GET', BUILTIN_MODELS_URL, new Uint8Array())
  const builtin = await fetch(BUILTIN_MODELS_URL, { headers: toHeaders(builtinSigned), signal })
    .then((r) => (r.ok ? r.json() : undefined))
    .catch(() => undefined)
  for (const entry of Array.isArray(builtin?.builtinModels) ? builtin.builtinModels : []) {
    const id = str(entry.model_name) || str(entry.id)
    if (id === '' || models.some((m) => m.id === id)) continue
    models.push({
      id,
      name: str(entry.display_name) || id,
      contextWindow: num(entry.context_length) ?? 0,
      maxOutput: num(entry.max_output_tokens) ?? 0,
      supportsImage: entry.supports_vision === true,
      isFree: false,
    })
  }

  if (models.length === 0) throw new FreeModelError(KIND.empty, `${WHAT} published no models`)
  return models
}

export async function chat(credential, request) {
  if (isExpired(credential)) throw new FreeModelError(KIND.auth, `${WHAT} credential expired; sign in again`)
  const keys = keysOf(credential)
  const url = `${CHAT_BASE}/chat/completions`
  const body = new TextEncoder().encode(
    JSON.stringify({ ...(request.body ?? {}), model: request.model, stream: request.body?.stream !== false }),
  )
  // A benefit model requires `maas_type: benefit`, and that header participates
  // in the signature — sending it unsigned fails verification just as surely as
  // omitting it.
  const extra = request.benefit === true ? { maas_type: 'benefit' } : undefined
  const signed = await signRequest(keys, 'POST', url, body, extra)
  const headers = toHeaders(signed)
  headers.set('accept', 'text/event-stream')
  let response
  try {
    response = await fetch(url, { method: 'POST', headers, body, signal: request.signal })
  } catch (error) {
    if (request.signal?.aborted === true || error?.name === 'AbortError') {
      throw new FreeModelError(KIND.aborted, `${WHAT} request was aborted`, { cause: error })
    }
    throw new FreeModelError(KIND.transport, `${WHAT} request failed: ${error?.message ?? error}`, { cause: error })
  }
  if (!response.ok) throw httpError(`${WHAT} request`, response, await readErrorBody(response))
  if (response.body === null) throw new FreeModelError(KIND.empty, `${WHAT} answered with no body`)
  return response
}

